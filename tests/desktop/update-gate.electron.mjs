import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {_electron as electron} from '/root/deepseek-harness/node_modules/.pnpm/playwright@1.61.1/node_modules/playwright/index.mjs';
const root=await fs.mkdtemp(path.join(os.tmpdir(),'mandatory-gate-'));
await fs.mkdir(path.join(root,'Easter Company'));
await fs.writeFile(path.join(root,'Easter Company/settings.json'),JSON.stringify({memoryMB:4096,server:'100.100.1.0:25565',autoUpdateLauncher:false,autoUpdateGame:false,exitOnLaunch:false}));
const app=await electron.launch({executablePath:path.resolve('node_modules/electron/dist/electron'),args:['--no-sandbox',path.resolve('tests/desktop/update-gate-harness.cjs')],env:{...process.env,EASTER_TEST_HOME:root}});
try{
 const page=await app.firstWindow();page.setDefaultTimeout(15000);
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.locator('#desktop-update[open]').waitFor();
 assert.equal(await page.evaluate(()=>document.body.classList.contains('is-arriving')),false,'arrival waits for mandatory updates');
 const status=await page.evaluate(()=>window.easterDesktop.status());
 assert.equal(status.startupReady,false);assert.equal(status.canPlay,false);
 assert.equal(status.settings.autoUpdateLauncher,true);assert.equal(status.settings.autoUpdateGame,true);
 for(const command of ['play','signIn','startInstall'])assert.match(await page.evaluate(async command=>{try{await window.easterDesktop[command]();return 'incorrectly allowed';}catch(error){return error.message;}},command),/Updates must finish/);
 await page.keyboard.press('Escape');assert.equal(await page.locator('#desktop-update').evaluate(el=>el.open),true,'Escape cannot bypass updates');
 await page.screenshot({path:'/tmp/launcher-update-checking.png',animations:'disabled'});
 await app.evaluate(()=>{global.easterUpdaterMode='offline';global.easterUpdaterContinue();});
 await page.getByRole('button',{name:'Retry update',exact:true}).waitFor();
 await page.screenshot({path:'/tmp/launcher-update-blocked.png',animations:'disabled'});
 assert.equal((await page.evaluate(()=>window.easterDesktop.status())).startupReady,false);
 await app.evaluate(()=>global.easterUpdaterMode='current');
 await page.getByRole('button',{name:'Retry update',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('#desktop-update').open);
 await page.keyboard.press('Escape');
 await page.locator('[data-desktop-play][data-action=download]').click();
 await page.locator('[data-desktop-play][data-action=signin]').click();
 await page.locator('.desktop-code').filter({hasText:'TEST'}).waitFor();
 await app.evaluate(()=>global.easterTestApprove());
 await page.locator('[data-desktop-play][data-action=play]').waitFor();
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 assert.equal(await page.locator('input[name=autoUpdateLauncher],input[name=autoUpdateGame]').count(),0,'no update opt-out controls');
 assert.equal(await page.locator('.desktop-launcher-update').count(),0,'no release-link substitute');
 assert.equal(await page.locator('input[name=exitOnLaunch]').count(),1);
 await page.screenshot({path:'/tmp/launcher-mandatory-settings.png',animations:'disabled'});
 await page.keyboard.press('Escape');
 await app.evaluate(()=>global.easterUpdaterMode='offline');
 await page.locator('[data-desktop-play][data-action=play]').click();
 await page.getByRole('button',{name:'Retry update',exact:true}).waitFor();
 assert.equal(await app.evaluate(()=>Boolean(global.easterTestGame)),false,'failed launcher check cannot start Minecraft');
 assert.equal((await page.evaluate(()=>window.easterDesktop.status())).canPlay,false);
 await app.evaluate(()=>{global.easterUpdaterMode='current';global.easterClientUpdateFail=true;});
 await page.getByRole('button',{name:'Retry update',exact:true}).click();
 await page.locator('#desktop-update p').filter({hasText:'Game manifest unavailable'}).waitFor();
 assert.equal((await page.evaluate(()=>window.easterDesktop.status())).canPlay,false,'game update failure also blocks Play');
 await app.evaluate(()=>global.easterClientUpdateFail=false);
 await page.getByRole('button',{name:'Retry update',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('#desktop-update').open);
 assert.equal((await page.evaluate(()=>window.easterDesktop.status())).canPlay,true,'successful retry restores ready state');
 const send=state=>app.evaluate(({BrowserWindow},state)=>BrowserWindow.getAllWindows()[0].webContents.send('launcher:state',state),state);
 await send({startupReady:false,launcherUpdate:{phase:'downloading',percent:47,version:'9.0.0',message:'Updating launcher…'}});
 await page.locator('#desktop-update [role=progressbar]').waitFor();
 assert.equal(await page.locator('#desktop-update [role=progressbar]').getAttribute('aria-valuenow'),'47');
 await page.screenshot({path:'/tmp/launcher-update-downloading.png',animations:'disabled'});
 await send({startupReady:false,launcherUpdate:{phase:'restarting',percent:100,message:'Restarting launcher…'}});
 assert.equal(await page.getByRole('button',{name:'Retry update',exact:true}).isVisible(),false);
 assert.deepEqual(errors,[]);
 console.log('Mandatory update gate PASS: no bypass, legacy false migrated, blocked/retry, delayed arrival, removed toggles/link, pre-Play launcher check.');
}finally{await app.close();await fs.rm(root,{recursive:true,force:true});}
