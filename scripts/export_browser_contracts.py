"""Export pure account/store contracts for buildless browser use. No Node bridge is exported."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def outputs():
    accounts = (ROOT / 'desktop/accounts.cjs').read_text()
    body = accounts[accounts.index('const DEFAULT_TIMEOUT='):accounts.index(' // ---- the game server,')]
    body += accounts[accounts.index(' // ---- the Community store'):accounts.index('module.exports=')]
    prefix = """// Generated by scripts/export_browser_contracts.py from desktop/accounts.cjs.
// Same validation and retry rules; browser transport never uses Electron IPC.
export const API_ORIGIN='https://jyjshd22z3.execute-api.us-east-2.amazonaws.com';
const apiOrigin=()=>API_ORIGIN;
const apiFetch=(url,options)=>fetch(url,{...options,credentials:'omit',cache:'no-store',redirect:'error',referrerPolicy:'no-referrer'});
const wait=(ms,value,{signal}={})=>new Promise((resolve,reject)=>{
 const stop=()=>{clearTimeout(timer);reject(new DOMException('Cancelled','AbortError'));};
 const timer=setTimeout(()=>{signal?.removeEventListener('abort',stop);resolve(value);},ms);
 if(signal?.aborted)stop();else signal?.addEventListener('abort',stop,{once:true});
});
"""
    yield 'site/account-client.mjs', prefix + body + '\nexport {AccountClient,AccountError,publicAccount,companySession,sanitizeAccount};\n'
    store = (ROOT / 'desktop/store.cjs').read_text()
    body = store[store.index('const SENTENCES='):store.index('// ---- The snapshot')]
    prefix = """// Generated by scripts/export_browser_contracts.py from desktop/store.cjs.
import {AccountError} from './account-client.mjs';
function stripeCheckoutURL(value){
 const url=new URL(value);
 if(url.origin!=='https://checkout.stripe.com'||url.username||url.password)throw Error('Invalid checkout');
 return url.href;
}
"""
    yield 'site/store-contract.mjs', prefix + body + '\nexport {catalogue,checkout,orders,refusal};\n'
if __name__ == '__main__':
    import sys
    for name, content in outputs():
        path = ROOT / name
        if '--check' in sys.argv:
            assert path.read_text() == content, name + ' is stale'
        else:
            path.write_text(content)
